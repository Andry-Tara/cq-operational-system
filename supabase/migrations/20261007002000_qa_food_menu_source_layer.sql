-- ============================================================
-- 1. NORMALIZATION HELPER
-- ============================================================

create or replace function
public.qa_food_normalize_name(
  p_value text
)
returns text
language sql
immutable
as $$
  select trim(
    regexp_replace(
      regexp_replace(
        lower(
          coalesce(
            p_value,
            ''
          )
        ),
        '[^a-z0-9]+',
        ' ',
        'g'
      ),
      '\s+',
      ' ',
      'g'
    )
  );
$$;


