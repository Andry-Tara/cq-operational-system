-- ============================================================
-- 6. BACKFILL EXISTING QA MENUS AS OBSERVATIONS
-- ============================================================

insert into public.qa_food_menu_observations (
  organization_id,
  canonical_menu_id,
  source,
  observation_key,
  source_menu_id,
  menu_name,
  normalized_name,
  category,
  is_variant,
  is_package,
  is_current_visible,
  first_seen_at,
  last_seen_at,
  raw_payload
)
select
  m.organization_id,
  m.id,
  m.source,
  m.source_menu_key,
  m.source_menu_key,
  m.name,
  public.qa_food_normalize_name(
    m.name
  ),
  m.category,
  false,
  false,
  case
    when m.source = 'HOTPOT_WEB'
      then true
    else null
  end,
  coalesce(
    m.first_seen_at,
    m.created_at
  ),
  coalesce(
    m.last_seen_at,
    m.updated_at
  ),
  jsonb_build_object(
    'bootstrap',
    true,
    'source',
    m.source,
    'source_menu_key',
    m.source_menu_key
  )
from public.qa_food_menus m
on conflict (
  organization_id,
  source,
  observation_key
)
do update set
  canonical_menu_id =
    excluded.canonical_menu_id,

  menu_name =
    excluded.menu_name,

  normalized_name =
    excluded.normalized_name,

  category =
    excluded.category,

  last_seen_at =
    greatest(
      public.qa_food_menu_observations.last_seen_at,
      excluded.last_seen_at
    ),

  updated_at =
    now();


-- ============================================================
-- 7. SOURCE SUMMARY VIEW
-- ============================================================

create or replace view
public.qa_food_menu_source_summary
as
select
  m.id as menu_id,
  m.organization_id,
  m.name,
  m.category,
  m.sku,
  m.lifecycle_status,
  m.current_web_visible,
  m.seen_in_api_orders,
  m.first_seen_at,
  m.last_seen_at,
  m.last_ordered_at,

  count(
    o.id
  ) as source_observation_count,

  count(
    distinct o.source
  ) as source_count,

  array_remove(
    array_agg(
      distinct o.source
    ),
    null
  ) as sources

from public.qa_food_menus m

left join public.qa_food_menu_observations o
  on o.canonical_menu_id =
     m.id

group by
  m.id,
  m.organization_id,
  m.name,
  m.category,
  m.sku,
  m.lifecycle_status,
  m.current_web_visible,
  m.seen_in_api_orders,
  m.first_seen_at,
  m.last_seen_at,
  m.last_ordered_at;


